        private void InitializeDocInfoDefaults()
        {
            if (_autoGenerateDocId && string.IsNullOrWhiteSpace(_docInfo.GetDocID()))
            {
                _docInfo.RandomDocID();
            }

            if (string.IsNullOrWhiteSpace(_docInfo.GetCreator()))
            {
                _docInfo.SetCreator(DefaultCreatorName);
            }

            if (string.IsNullOrWhiteSpace(_docInfo.GetCreatorVersion()))
            {
                _docInfo.SetCreatorVersion(DefaultCreatorVersion);
            }

            if (_docInfo.GetOfdElement("CreationDate") == null)
            {
                _docInfo.SetCreationDate(DateTime.Now);
            }

            if (_docInfo.GetOfdElement("ModDate") == null)
            {
                _docInfo.SetModDate(DateTime.Now);
            }
        }

        private CtDocInfo BuildDocInfoSnapshot()
        {
            var snapshot = new CtDocInfo(new XElement(_docInfo.Element));
            EnsureDocInfoDefaults(snapshot);
            return snapshot;
        }

        private void EnsureDocInfoDefaults(CtDocInfo target)
        {
            if (_autoGenerateDocId && (target.GetOfdElement("DocID") == null || string.IsNullOrWhiteSpace(target.GetDocID())))
            {
                target.RandomDocID();
            }

            if (target.GetOfdElement("Creator") == null || string.IsNullOrWhiteSpace(target.GetCreator()))
            {
                target.SetCreator(DefaultCreatorName);
            }

            if (target.GetOfdElement("CreatorVersion") == null || string.IsNullOrWhiteSpace(target.GetCreatorVersion()))
            {
                target.SetCreatorVersion(DefaultCreatorVersion);
            }

            if (target.GetOfdElement("CreationDate") == null)
            {
                target.SetCreationDate(DateTime.Now);
            }

            if (target.GetOfdElement("ModDate") == null)
            {
                target.SetModDate(DateTime.Now);
            }
        }

        private static string IndentXml(string xml, int spaces)
        {
            if (string.IsNullOrEmpty(xml))
            {
                return string.Empty;
            }

            var indent = new string(' ', spaces);
            return indent + xml.Replace("\n", "\n" + indent);
        }
