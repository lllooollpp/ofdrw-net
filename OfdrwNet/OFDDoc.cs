        #region 生成/关闭
        public async Task CloseAsync()
        {
            if (_disposed)
                return;
            try
            {
                if (_streamQueue.Count > 0 || _rawImages.Count > 0)
                {
                    // Simplified: treat all raw additions as a single virtual page for now
                    var vp = new OfdrwNet.Models.VirtualPage(_pageLayout);
                    foreach (var item in _streamQueue)
                    {
                        // This part needs a proper layout engine to place elements.
                        // For now, we just add them to a virtual page.
                    }
                    _virtualPageList.Add(vp);
                }

                if (_virtualPageList.Count == 0)
                    _virtualPageList.Add(new OfdrwNet.Models.VirtualPage(_pageLayout));

                await GenerateDocumentAsync();
            }
            finally
            {
                _disposed = true;
                _ofdContainer.Dispose();
            }
        }

        private async Task GenerateDocumentAsync()
        {
            if (!string.IsNullOrEmpty(_outPath))
            {
                await GenerateOfdContentAsync(_outPath);
            }
            else if (_outStream != null)
            {
                await GenerateOfdContentAsync(_outStream);
            }
            else
                throw new InvalidOperationException("未设置输出");
        }

        private async Task GenerateOfdContentAsync(string outputPath)
        {
            var tempDir = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString());
            Directory.CreateDirectory(tempDir);
            try
            {
                await CreateOfdStructureAsync(tempDir);
                if (File.Exists(outputPath))
                    File.Delete(outputPath);

                // 检查输出路径是目录还是文件
                if (Directory.Exists(outputPath) || Path.GetExtension(outputPath).ToLowerInvariant() != ".ofd")
                {
                    // 如果是目录或没有.ofd扩展名，则复制文件到目录
                    if (!Directory.Exists(outputPath))
                    {
                        Directory.CreateDirectory(outputPath);
                    }
                    // 复制所有文件
                    foreach (var file in Directory.GetFiles(tempDir, "*", SearchOption.AllDirectories))
                    {
                        var relativePath = Path.GetRelativePath(tempDir, file);
                        var destFile = Path.Combine(outputPath, relativePath);
                        var destDir = Path.GetDirectoryName(destFile);
                        if (!string.IsNullOrEmpty(destDir) && !Directory.Exists(destDir))
                            Directory.CreateDirectory(destDir);
                        File.Copy(file, destFile, true);
                    }
                    _logger?.LogInformation("[OFDDoc][GenerateOfdContentAsync] OFD文件已复制到目录: {OutputPath}", outputPath);
                }
                else
                {
                    // 如果是.ofd文件，则创建ZIP
                    ZipFile.CreateFromDirectory(tempDir, outputPath);
                    _logger?.LogInformation("[OFDDoc][GenerateOfdContentAsync] OFD文件已创建: {OutputPath}", outputPath);
                }
            }
            finally { if (Directory.Exists(tempDir)) Directory.Delete(tempDir, true); }
        }

        private async Task GenerateOfdContentAsync(Stream outputStream)
        {
            var tempDir = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString());
            Directory.CreateDirectory(tempDir);
            try
            {
                await CreateOfdStructureAsync(tempDir);
                using var archive = new ZipArchive(outputStream, ZipArchiveMode.Create, true);
                foreach (var file in Directory.GetFiles(tempDir, "*", SearchOption.AllDirectories))
                {
                    var entryName = Path.GetRelativePath(tempDir, file).Replace('\\', '/');
                    var entry = archive.CreateEntry(entryName);
                    using var entryStream = entry.Open();
                    using var fileStream = File.OpenRead(file);
                    await fileStream.CopyToAsync(entryStream);
                }
            }
            finally { if (Directory.Exists(tempDir)) Directory.Delete(tempDir, true); }
        }

        private async Task CreateOfdStructureAsync(string baseDir)
        {
            if (_pageGroups == null)
            {
                var pgBuilder = new OfdrwNet.Services.PageGroupBuilder(_logger);
                _pageGroups = pgBuilder.Build(_streamQueue, _virtualPageList, _rawImages, _rawPaths);
            }
            _logger?.LogDebug("[OFD][CreateStructure] Pages={PageCount}", _pageGroups?.Count);
            // 使用 Core 中的模型类构建 OFD.xml 而不是直接字符串拼接
            // 引用: OfdrwNet.Core.BasicStructure.Ofd.OFD / DocBody / CtDocInfo 以及 BasicType.StLoc
            var docInfoSnapshot = BuildDocInfoSnapshot();
            try
            {
                var docBody = new DocBody()
                    .SetDocInfo(docInfoSnapshot)
                    .SetDocRoot(new StLoc($"{DocDirectoryName}/Document.xml"));

                var ofd = new OFD(docBody).SetVersion(_ofdVersion);
                var ofdXml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n" + ofd.ToXml();
                await FileUtil.WriteTextFileUtf8LfAsync(Path.Combine(baseDir, "OFD.xml"), ofdXml);
            }
            catch (Exception ex)
            {
                _logger?.LogError(ex, "[OFDDoc][CreateOfdStructureAsync] 构建 OFD.xml 失败，回退到最小结构");
                var fallbackInfo = BuildDocInfoSnapshot();
                var fallbackBuilder = new StringBuilder();
                fallbackBuilder.AppendLine("<?xml version=\"1.0\" encoding=\"UTF-8\"?>");
                fallbackBuilder.AppendLine($"<ofd:OFD xmlns:ofd=\"http://www.ofdspec.org/2016\" DocType=\"OFD\" Version=\"{_ofdVersion}\">");
                fallbackBuilder.AppendLine("  <ofd:DocBody>");
                fallbackBuilder.AppendLine(IndentXml(fallbackInfo.ToXml(), 4));
                fallbackBuilder.AppendLine($"    <ofd:DocRoot>{DocDirectoryName}/Document.xml</ofd:DocRoot>");
                fallbackBuilder.AppendLine("  </ofd:DocBody>");
                fallbackBuilder.AppendLine("</ofd:OFD>");
                await FileUtil.WriteTextFileUtf8LfAsync(Path.Combine(baseDir, "OFD.xml"), fallbackBuilder.ToString());
            }
            var docDir = Path.Combine(baseDir, DocDirectoryName);
            Directory.CreateDirectory(docDir);
            _logger?.LogInformation("[OFDDoc][CreateOfdStructureAsync] 准备调用GenerateResourcesAsync DocDir={DocDir}", docDir);
            await GenerateResourcesAsync(docDir);
            _logger?.LogInformation("[OFDDoc][CreateOfdStructureAsync] GenerateResourcesAsync调用完成");
            var pagesDir = Path.Combine(docDir, "Pages");
            Directory.CreateDirectory(pagesDir);
            // 先生成页面文件（页面和内容会为对象分配ID），再生成 Document.xml，以便 MaxUnitID 能覆盖所有ID
            await GeneratePageFilesAsync(pagesDir);
            var documentXml = await GenerateDocumentXmlAsync();
            await FileUtil.WriteTextFileUtf8LfAsync(Path.Combine(docDir, "Document.xml"), documentXml);
            _logger?.LogInformation("[OFDDoc][CreateOfdStructureAsync] 准备调用PostGenerationFixAsync");
            await PostGenerationFixAsync(baseDir);
            _logger?.LogInformation("[OFDDoc][CreateOfdStructureAsync] PostGenerationFixAsync调用完成");
        }

        private async Task<string> GenerateDocumentXmlAsync()
        {
            if (_pageGroups == null)
            {
                var pgBuilder = new OfdrwNet.Services.PageGroupBuilder(_logger);
                _pageGroups = pgBuilder.Build(_streamQueue, _virtualPageList, _rawImages, _rawPaths);
            }
            if (_pageGroups == null)
                _pageGroups = new List<(int PageNumber, List<object> Items)>();
            // 使用 Core 模型构建 Document.xml
            // 1. 创建 CommonData，包括 MaxUnitID、PageArea、公共/文档资源引用
            var commonData = new OfdrwNet.Core.BasicStructure.Doc.CtCommonData()
                .SetMaxUnitId((long)_maxUnitID)
                .SetPageArea(new OfdrwNet.Core.BasicStructure.Doc.CtPageArea(0, 0, _pageLayout.Width, _pageLayout.Height));
            if (!string.IsNullOrEmpty(_publicResRelativePath))
            {
                commonData.AddPublicRes(new OfdrwNet.Core.BasicType.StLoc(_publicResRelativePath));
            }
            if (!string.IsNullOrEmpty(_documentResRelativePath))
            {
                commonData.AddDocumentRes(new OfdrwNet.Core.BasicType.StLoc(_documentResRelativePath));
            }

            // 2. 创建 Pages 集合，并为每页分配 ID（与原先逻辑一致：调用 GetNextID）
            var orderedPages = _pageGroups.OrderBy(p => p.PageNumber).ToList();
            var pagesElement = new OfdrwNet.Core.BasicStructure.PageTree.Pages();
            foreach (var pg in orderedPages)
            {
                var pid = GetNextID();
                var pageIndex = Math.Max(pg.PageNumber - 1, 0);
                pagesElement.AddPage(new OfdrwNet.Core.BasicStructure.PageTree.Page(pid, $"Pages/Page_{pageIndex}/Content.xml"));
            }

            // 注意：上面分配页面ID时调用了 GetNextID 可能会提升 _maxUnitID，需要更新 CommonData 的 MaxUnitID
            if (_maxUnitID < 0)
                _maxUnitID = 0; // 防御性
            // 重新覆盖最新 MaxUnitID
            commonData.SetMaxUnitId((long)_maxUnitID);

            // 3. 创建 Document 根并附加 CommonData 和 Pages
            var document = new OfdrwNet.Core.BasicStructure.Doc.Document()
                .SetCommonData(commonData)
                .SetPages(pagesElement);

            // 4. 输出 XML 字符串（添加 XML 声明）
            var xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n" + document.ToXml();
            await Task.CompletedTask;
            return xml;
        }

        private async Task GeneratePageFilesAsync(string pagesDir)
        {
            if (_fontMap.Count == 0)
            {
                var fontRegistry = new OfdrwNet.Font.OfdFontRegistry(_logger);
                foreach (var kv in fontRegistry.Build(_externalFontFiles, _streamQueue))
                    _fontMap[kv.Key] = kv.Value;
            }
            if (_pageGroups == null)
            {
                var pgBuilder = new OfdrwNet.Services.PageGroupBuilder(_logger);
                _pageGroups = pgBuilder.Build(_streamQueue, _virtualPageList, _rawImages, _rawPaths);
            }
            var writer = new OfdrwNet.Services.PageContentWriter(_logger);
            foreach (var pg in _pageGroups)
            {
                var pageIndex = Math.Max(pg.PageNumber - 1, 0);
                await writer.WritePageAsync(pagesDir, pg.PageNumber, pageIndex, pg.Items, _rawImages, _rawPaths, _fontMap, _imageOrderingStrategy, GetNextID, _pageLayout.Width, _pageLayout.Height);
            }
        }

        private void BuildFontMap()
        {
            _fontMap.Clear();
            int id = 1;
            var fontNames = _streamQueue.OfType<RawGlyphRun>().Select(rg => rg.FontName)
                                      .Concat(_externalFontFiles.Keys)
                                      .Distinct(StringComparer.OrdinalIgnoreCase);

            foreach (var name in fontNames)
            {
                if (!_fontMap.ContainsKey(name))
                {
                    _fontMap[name] = new OfdFont(id++, name, name);
                }
            }
            if (_fontMap.Count == 0)
                _fontMap["SimSun"] = new OfdFont(1, "SimSun", "宋体");
        }

        private async Task GenerateResourcesAsync(string docDir)
        {
            BuildFontMap();
            var generator = new OfdrwNet.Services.ResourceGenerator(_logger);
